def main():
    raiz = pathlib.Path(__file__).resolve().parent.parent
    out = []
    for i, p in enumerate(PROBLEMAS, 1):
        d = dict(p, id=i)
        d["url"] = "https://es.wikipedia.org/wiki/" + d.pop("wiki")
        out.append(d)
    (raiz / "data" / "enfermedades.json").write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"{len(out)} problemas → data/enfermedades.json")


if __name__ == "__main__":
    main()
